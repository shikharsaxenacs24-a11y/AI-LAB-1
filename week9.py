# Initialize Knowledge Base
KB = [
    {"~food(Peanuts)", "likes(John,Peanuts)"},
    {"~eats(Anil,Peanuts)", "killed(Anil)", "food(Peanuts)"},
    {"~alive(Anil)", "~killed(Anil)"},
    {"eats(Anil,Peanuts)"},
    {"alive(Anil)"},
    {"~likes(John,Peanuts)"}
]

# Resolution Function
def resolve(c1, c2):
    new_clauses = set()

    for l1 in c1:
        for l2 in c2:
            if l1 == "~" + l2 or l2 == "~" + l1:
                clause = (c1 | c2) - {l1, l2}
                new_clauses.add(frozenset(clause))

    return new_clauses

# Apply Resolution
while True:
    new = set()

    for i in range(len(KB)):
        for j in range(i + 1, len(KB)):
            new.update(resolve(KB[i], KB[j]))

    if frozenset() in new:
        print("Goal Proved")
        break

    new -= set(map(frozenset, KB))

    if not new:
        print("Goal Not Proved")
        break

    KB.extend([set(c) for c in new])