def unify(x, y, subst={}):
    if x == y:
        return subst

    if isinstance(x, str) and x.islower():
        subst[x] = y
        return subst

    if isinstance(y, str) and y.islower():
        subst[y] = x
        return subst

    if isinstance(x, tuple) and isinstance(y, tuple):
        if x[0] != y[0] or len(x) != len(y):
            return "Failure"

        for a, b in zip(x[1:], y[1:]):
            subst = unify(a, b, subst)
            if subst == "Failure":
                return "Failure"
        return subst

    return "Failure"


exp1 = ('Eats', 'x', 'Apple')
exp2 = ('Eats', 'Riya', 'y')

print(unify(exp1, exp2, {}))