# Initialize Knowledge Base
KB = {
    ("American", "Robert"),
    ("Enemy", "A", "America"),
    ("Owns", "A", "T1"),
    ("Missile", "T1")
}

# Forward Chaining
while True:
    new_facts = set()

    for fact in KB:
        if fact[0] == "Enemy":
            new_facts.add(("Hostile", fact[1]))

        if fact[0] == "Missile":
            new_facts.add(("Weapon", fact[1]))

    if ("Missile", "T1") in KB and ("Owns", "A", "T1") in KB:
        new_facts.add(("Sells", "Robert", "T1", "A"))

    if (("American", "Robert") in KB and
        ("Weapon", "T1") in KB and
        ("Sells", "Robert", "T1", "A") in KB and
        ("Hostile", "A") in KB):

        new_facts.add(("Criminal", "Robert"))

    if new_facts.issubset(KB):
        break

    KB.update(new_facts)

# Check Goal
if ("Criminal", "Robert") in KB:
    print("Robert is Criminal")
else:
    print("Goal Not Proved")